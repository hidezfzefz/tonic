// Build script for the M1 spike.
//
// Two jobs:
//   1. Ask the host compiler for the real ABI sizes, then emit them as Rust
//      constants. bionic.rs asserts those values against the glibc layout we
//      claim to support, so a host that drifts fails the build instead of
//      corrupting pthread state at run time.
//   2. Build a small synthetic shared object ("fixture") that exercises the
//      loader: PT_LOAD mapping, RELA relocations, init_array constructors, a
//      TLS symbol and undefined imports resolved by the host.
//
// No external crates: this must build offline inside a Flatpak sandbox.

use std::env;
use std::fs;
use std::path::PathBuf;
use std::process::Command;

fn main() {
    println!("cargo:rerun-if-changed=csrc/probe.c");
    println!("cargo:rerun-if-changed=csrc/fixture.c");
    println!("cargo:rerun-if-changed=../../third_party/aosp/bits_sysconf.h");
    println!("cargo:rerun-if-env-changed=CC");

    let out = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR is set by cargo"));
    let cc = env::var("CC").unwrap_or_else(|_| "cc".to_string());

    build_abi_probe(&cc, &out);
    build_fixture(&cc, &out);
    build_sysconf_table(&out);
}

fn run(cmd: &mut Command, what: &str) {
    let status = cmd.status().unwrap_or_else(|e| panic!("{what}: failed to spawn: {e}"));
    if !status.success() {
        panic!("{what}: compiler exited with {status}");
    }
}

fn build_abi_probe(cc: &str, out: &PathBuf) {
    let bin = out.join("tonic-abi-probe");
    run(
        Command::new(cc)
            .arg("-O0")
            .arg("-o")
            .arg(&bin)
            .arg("csrc/probe.c"),
        "building ABI probe",
    );

    let output = Command::new(&bin)
        .output()
        .unwrap_or_else(|e| panic!("running ABI probe: {e}"));
    if !output.status.success() {
        panic!(
            "ABI probe failed: {}",
            String::from_utf8_lossy(&output.stderr)
        );
    }

    let mut generated = String::from("// Generated by build.rs from the host compiler. Do not edit.\n");
    for line in String::from_utf8_lossy(&output.stdout).lines() {
        let Some((key, value)) = line.split_once('=') else {
            continue;
        };
        let (key, value) = (key.trim(), value.trim());
        if key.is_empty() || value.is_empty() {
            continue;
        }
        let Ok(number) = value.parse::<usize>() else {
            panic!("ABI probe returned a non-numeric value for {key}: {value}");
        };
        generated.push_str(&format!("pub const {key}: usize = {number};\n"));
    }
    fs::write(out.join("host_abi.rs"), generated).expect("write host_abi.rs");
}

fn build_fixture(cc: &str, out: &PathBuf) {
    let dir = out.join("fixtures");
    fs::create_dir_all(&dir).expect("create fixtures dir");
    let so = dir.join("libfixture.so");

    // -nostdlib: the fixture must not drag glibc in; every external symbol is
    // resolved through the loader's provider, which is the thing under test.
    // -z now -z relro: force the relocation/RELRO paths.
    run(
        Command::new(cc)
            .args([
                "-O0",
                "-fPIC",
                "-shared",
                "-nostdlib",
                "-Wl,-soname,libfixture.so",
                "-Wl,-z,relro",
                "-Wl,-z,now",
                "-o",
            ])
            .arg(&so)
            .arg("csrc/fixture.c"),
        "building loader fixture",
    );

    println!(
        "cargo:rustc-env=TONIC_FIXTURE={}",
        so.display()
    );
}

fn build_sysconf_table(out: &PathBuf) {
    let header = PathBuf::from("../../third_party/aosp/bits_sysconf.h");
    let mut entries: Vec<(i32, String)> = Vec::new();

    if let Ok(text) = fs::read_to_string(&header) {
        for line in text.lines() {
            let line = line.trim();
            let Some(rest) = line.strip_prefix("#define") else {
                continue;
            };
            let mut parts = rest.split_whitespace();
            let Some(name) = parts.next() else { continue };
            let Some(value) = parts.next() else { continue };
            let Some(name) = name.strip_prefix("_SC_") else {
                continue;
            };
            // AOSP writes its selectors in hex (`0x0027`); aliases such as
            // `#define _SC_PAGESIZE _SC_PAGE_SIZE` have no number and are
            // skipped, leaving the canonical numeric definition.
            let parsed = if let Some(hex) = value
                .strip_prefix("0x")
                .or_else(|| value.strip_prefix("0X"))
            {
                i32::from_str_radix(hex.trim_end_matches(['u', 'U', 'l', 'L']), 16).ok()
            } else {
                value.parse::<i32>().ok()
            };
            let Some(number) = parsed else {
                continue;
            };
            entries.push((number, name.to_string()));
        }
    }

    // PAGESIZE = 39 is the one selector the brief depends on: on glibc, 39 is
    // _SC_BC_STRING_MAX, so passing it through unchanged tells the engine the
    // page size is 1000. Keep it even when the AOSP header is absent.
    if !entries.iter().any(|(_, name)| name == "PAGESIZE") {
        entries.push((39, "PAGESIZE".to_string()));
    }
    entries.sort_by_key(|(number, _)| *number);
    entries.dedup_by_key(|(number, _)| *number);

    let mut generated = String::from(
        "// Generated by build.rs from third_party/aosp/bits_sysconf.h.\n\
         // AOSP bionic libc, Apache-2.0. Numeric selectors only.\n\
         pub static BIONIC_SYSCONF: &[(i32, &str)] = &[\n",
    );
    for (number, name) in entries {
        generated.push_str(&format!("    ({number}, \"{name}\"),\n"));
    }
    generated.push_str("];\n");
    fs::write(out.join("bionic_sysconf.rs"), generated).expect("write bionic_sysconf.rs");
}
